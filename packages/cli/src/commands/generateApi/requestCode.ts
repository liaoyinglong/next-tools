import * as os from 'os';
import { camelCase } from 'es-toolkit';
import type { OpenAPIV3 } from 'openapi-types';
import type { ApiConfig } from '../../shared/config';
import {
  generateToRequestCode,
  parseRequestParameters,
} from './requestParameters';
import { compileRequestParams, compileResponseParams } from './typeCompiler';

/**
 * 根据请求方法，生成请求代码
 */
export async function generateApiRequestCode(options: {
  url: string;
  method: string;
  operationObject: OpenAPIV3.OperationObject;
  pathItemParameters?: (
    | OpenAPIV3.ParameterObject
    | OpenAPIV3.ReferenceObject
  )[];
  apiConfig: ApiConfig;
}): Promise<string> {
  const { method, operationObject, pathItemParameters, apiConfig } = options;

  const url = (() => {
    if (typeof apiConfig.urlTransformer === 'string') {
      return `${apiConfig.urlTransformer}${options.url}`;
    }
    if (typeof apiConfig.urlTransformer === 'function') {
      return apiConfig.urlTransformer(options.url);
    }
    return options.url;
  })();

  const seeUrl = apiConfig.swaggerUiUrl
    ? `${apiConfig.swaggerUiUrl}#/${encodeURIComponent(
        `${operationObject.tags?.join('/') ?? ''}/${
          operationObject.operationId
        }`,
      )}`
    : '';

  // 生成的请求构造器的名称，需要使用原始 url
  let requestBuilderName = camelCase(`${options.url}_${method}_api`);

  // 判断是否有效的 js 变量
  if (!/^[a-zA-Z_$][0-9a-zA-Z_$]*$/.test(requestBuilderName)) {
    // 不是有效的 js 变量，使用 _ + 数字
    requestBuilderName = `_${requestBuilderName}`;
  }

  const parsedParams = parseRequestParameters(
    operationObject,
    pathItemParameters,
  );
  const toRequestCode = generateToRequestCode(parsedParams, method);

  const [requestParamsTypeCode, responseParamsTypeCode] = apiConfig.enableTs
    ? await Promise.all([
        compileRequestParams(operationObject, apiConfig, parsedParams),
        compileResponseParams(operationObject, apiConfig),
      ])
    : [undefined, undefined];

  let code: string[] = [
    '// do not edit this file manually, it will be overwritten by @dune2/cli',
    apiConfig.RequestBuilderImportPath!,
    apiConfig.queryClientImportPath!,

    '/**',
    `  * ${operationObject.summary}`,
    `  * @tags ${operationObject.tags?.join(',')}`,
    seeUrl && `  * @see ${seeUrl}`,
    `  */`,
  ].filter(Boolean);

  // builder 代码
  const builderFields = [
    `  url: '${url}',`,
    `  method: '${method}',`,
    toRequestCode && `  ${toRequestCode}`,
    apiConfig.queryClientImportPath && '  queryClient,',
  ].filter(Boolean);

  let builderCode = `export const ${requestBuilderName} = new RequestBuilder({\n${builderFields.join('\n')}\n});`;
  if (apiConfig.enableTs) {
    builderCode = builderCode.replace(
      'new RequestBuilder(',
      `new RequestBuilder<${requestBuilderName}.Req, ${requestBuilderName}.Res>(`,
    );
  }
  code.push(builderCode);

  if (apiConfig.enableTs && requestParamsTypeCode && responseParamsTypeCode) {
    code.push(`
export namespace ${requestBuilderName} {
 ${requestParamsTypeCode.code}
 
 ${responseParamsTypeCode.code}
};`);

    if (requestParamsTypeCode.enumsCode) {
      code.push(
        `\nexport const ${requestBuilderName}ReqEnums = ${requestParamsTypeCode.enumsCode} as const;`,
      );
    }
    if (responseParamsTypeCode.enumsCode) {
      code.push(
        `\nexport const ${requestBuilderName}ResEnums = ${responseParamsTypeCode.enumsCode} as const;`,
      );
    }
  }

  return code.join(os.EOL);
}
